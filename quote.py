main_keyboard = ReplyKeyboardMarkup(
    keyboard=[
        [KeyboardButton(text="🎲 Случайная цитата")]
    ],
    resize_keyboard=True
)

@dp.message(Command("start"))
async def start_handler(message: types.Message):
    await message.answer(
        "Привет, Арт! Я твой личный бот-копилка с цитатами. Нажми кнопку ниже, чтобы получить случайную мысль.",
        reply_markup=main_keyboard
    )

@dp.message()
async def send_quote(message: types.Message):
    if message.text == "🎲 Случайная цитата":
        random_quote = random.choice(QUOTES)
        await message.answer(random_quote)
    else:
        await message.answer("Нажми на кнопку ниже, чтобы получить цитату 👇", reply_markup=main_keyboard)

async def main():
    print("Бот успешно запущен!")
    await dp.start_polling(bot)

if __name__ == "__main__":
    asyncio.run(main())